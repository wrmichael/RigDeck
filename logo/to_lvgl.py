import sys, numpy as np
from PIL import Image
out=open(sys.argv[1],'w')
out.write('// Gold splash logos (Audiowide font, SIL Open Font License 1.1), generated by tools/gold_logo.py.\n// LVGL I8: 256-colour palette (B,G,R,A) followed by one byte per pixel.\n#include "lvgl.h"\n\n')
for name,path in zip(sys.argv[2::2],sys.argv[3::2]):
    im=Image.open(path).convert('RGB')
    a=np.asarray(im).max(axis=2); ys,xs=np.where(a>6)
    box=(max(0,xs.min()-4),max(0,ys.min()-4),min(im.width,xs.max()+5),min(im.height,ys.max()+5))
    im=im.crop(box)
    q=im.quantize(colors=256,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    pal=q.getpalette()[:768]; pal+= [0]*(768-len(pal))
    px=np.asarray(q,np.uint8)
    w,h=q.size
    data=bytearray()
    for i in range(256): r,g,b=pal[3*i:3*i+3]; data+=bytes([b,g,r,255])
    data+=px.tobytes()
    out.write(f'static const uint8_t {name}_map[] = {{\n')
    for i in range(0,len(data),24): out.write('    '+','.join(str(x) for x in data[i:i+24])+',\n')
    out.write('};\n')
    out.write(f'const lv_image_dsc_t {name} = {{\n    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I8, .flags = 0, .w = {w}, .h = {h}, .stride = {w}}},\n    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n\n')
    print(name,w,h,len(data))
    q.convert('RGB').save(path.replace('.png','_q.png'))
