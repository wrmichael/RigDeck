#!/usr/bin/env python3
"""Builds main/map_data.c: country, state/province and lake outlines for the APRS map.

Source: Natural Earth 1:50m (public domain, https://www.naturalearthdata.com), GeoJSON from
github.com/nvkelso/natural-earth-vector: ne_50m_admin_0_countries, ne_50m_admin_1_states_provinces_lakes,
ne_50m_lakes. Usage: python3 tools/make_map.py <folder with those .geojson files>

Format ("RDM1"): u32 polyline count, then per polyline: u8 class (0 country/coast, 1 state/province, 2 lake),
u16 points, i16 lat/lon bounding box (min lat, min lon, max lat, max lon), i16 first lat, i16 first lon, then
(points-1) steps as int8 dlat, int8 dlon; a step that does not fit is -128 followed by int16 dlat, int16 dlon.
Units: 0.01 degree. Little endian.
"""
import json, struct, sys, os

TOL = {0: 3.5, 1: 3.0, 2: 3.0}          # Douglas-Peucker tolerance in 0.01 degree (about 3 km)

def rdp(pts, eps):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        L = (dx * dx + dy * dy) ** 0.5
        best, bi = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / L if L else ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
            if d > best: best, bi = d, i
        if best > eps:
            keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

def rings(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    for p in polys:
        for r in p: yield r

def main(src):
    out = []
    def add(path, cls, flt=lambda p: True):
        d = json.load(open(os.path.join(src, path)))
        for ft in d['features']:
            if not flt(ft['properties']): continue
            for r in rings(ft['geometry']):
                pts = [(round(lat * 100), round(lon * 100)) for lon, lat in r]
                q = []
                for p in pts:
                    if not q or q[-1] != p: q.append(p)
                q = rdp(q, TOL[cls])
                parts, cur = [], [q[0]]                       # split where a ring jumps across the 180th meridian
                for a, c in zip(q, q[1:]):
                    if abs(c[1] - a[1]) > 9000: parts.append(cur); cur = [c]
                    else: cur.append(c)
                parts.append(cur)
                for part in parts:
                    if len(part) >= 2: out.append((cls, part))
    add('ne_50m_admin_0_countries.geojson', 0)
    add('ne_50m_admin_1_states_provinces_lakes.geojson', 1)
    add('ne_50m_lakes.geojson', 2, lambda p: (p.get('scalerank') if p.get('scalerank') is not None else 9) <= 2)
    b = bytearray(b'RDM1') + struct.pack('<I', len(out))
    npts = 0
    for cls, q in out:
        la = [p[0] for p in q]; lo = [p[1] for p in q]
        b += struct.pack('<BHhhhh', cls, len(q), min(la), min(lo), max(la), max(lo))
        b += struct.pack('<hh', q[0][0], q[0][1])
        for (a0, o0), (a1, o1) in zip(q, q[1:]):
            da, do = a1 - a0, o1 - o0
            if -127 <= da <= 127 and -127 <= do <= 127: b += struct.pack('<bb', da, do)
            else: b += struct.pack('<bhh', -128, da, do)
        npts += len(q)
    lines = ['// Generated by tools/make_map.py from Natural Earth 1:50m (public domain). Do not edit.',
             '#include <stdint.h>', '#include <stddef.h>',
             '#ifdef __cplusplus', 'extern "C" {', '#endif',
             'extern const uint8_t g_mapData[];', 'extern const size_t g_mapDataLen;',
             'const uint8_t g_mapData[] = {']
    for i in range(0, len(b), 24):
        lines.append('    ' + ','.join(str(x) for x in b[i:i + 24]) + ',')
    lines += ['};', 'const size_t g_mapDataLen = sizeof g_mapData;', '#ifdef __cplusplus', '}', '#endif', '']
    open(os.path.join(os.path.dirname(__file__), '..', 'main', 'map_data.c'), 'w').write('\n'.join(lines))
    print(f'{len(out)} polylines, {npts} points, {len(b)} bytes')

main(sys.argv[1])
